/** Wooting's special `usageId` values that are not plain HID usages. */
const SPECIAL_USAGE: Readonly<Record<number, number>> = {
  0x401: 4207, // brightness up
  0x402: 4208, // brightness down
  0x409: 40961, // Function/Fn key (Zetsu's vendor usage)
};

/** Convert a Wooting key code to the usage value used by Zetsu remap writes. */
export function wootingKeycodeToUsage(code: number): number | null {
  const raw = WOOTING_KEYCODE_USAGE[code];
  if (raw === undefined) return null;
  if (raw >= 0x300 && raw < 0x400) return 0x1000 | (raw & 0xff);
  if (raw >= 0x400) return SPECIAL_USAGE[raw] ?? null;
  return raw;
}

/** True when the code is known to the 60HE/80HE key catalogue. */
export function isKnownWootingKeycode(code: number): boolean {
  return WOOTING_KEYCODE_USAGE[code] !== undefined;
}

