/** Look up a catalogue entry by textCode or HID usage. */
export function findKey(value) {
  if (typeof value === 'number') return KEY_CATALOG.find((key) => key.hidCode === value) ?? null;
  return KEY_CATALOG.find((key) => key.textCode === value) ?? null;
}
